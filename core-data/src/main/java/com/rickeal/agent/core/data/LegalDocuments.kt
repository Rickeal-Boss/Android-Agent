/**
 * 合规文本与授权链接的**唯一**来源。
 *
 * ## 为什么放在 `:core-data`
 *
 * 同一份文本有三处消费方：
 *  - `:app` —— 首启引导里的「应用服务条款」步骤；
 *  - `:feature-models` —— 下载 / 加载 Gemma 模型时的授权闸门；
 *  - `:feature-settings` —— 「条款与授权」回看页。
 *
 * `:app` 是叶子模块（feature 模块看不到它），所以文本不能留在 app 里；而 `:core-data`
 * 是三者共同的依赖。更重要的是：**同意的状态**（[SettingsRepository] 里的
 * `is_tos_accepted` / `is_gemma_terms_accepted`）本来就存在这里 ——
 * 状态与它对应的文本放在一起，才不会出现「改了条款正文、状态位还是旧语义」这类漂移。
 *
 * ## 设计原则（重要，别改这条）
 *
 * 这里只放「框架」，不放「条款」。我们不是法务，自行起草的条款既没有法律效力，
 * 反而会把风险从「缺少条款」变成「有了一份写得不对的条款」，后者更糟。因此：
 *
 *  - 正文一律是**明确的占位文本**，并在注释里标注需由法务替换；
 *  - 能给出官方原文链接的（Gemma Terms of Use），一律用**外链**，绝不代拟、不改写；
 *  - 对话框 / 步骤 / 状态机 / 持久化这套「框架」是完整的，只有正文是占位。
 *
 * 替换正文时只改这个文件即可，三个消费方的 UI 都不需要动。
 */
