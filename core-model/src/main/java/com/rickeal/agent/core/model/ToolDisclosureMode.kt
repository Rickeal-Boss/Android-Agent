package com.rickeal.agent.core.model

import kotlinx.serialization.Serializable

/**
 * 工具**披露模式**（Wave 27 / Operit「CLI 工具模式」裁剪移植）。
 *
 * ## 为什么需要它
 * 在引入本模式之前，全部已启用工具的完整清单（名称 + 描述 + 参数名）会被**一次性**
 * 拼进系统提示词。工具一多就有两个代价：
 *  1. **预算**：工具段是最长的 section 之一，直接挤占端侧小模型本就有限的上下文。
 *  2. **回显风险**：Wave 21 真机实测过 —— SmolVLM2-500M 会把工具清单段当成模板
 *     逐字复述再退化刷屏（详见 `StreamRepetitionDetector` 的 `prompt_echo` 判定）。
 *     工具段越长，被当成「待续写文本」的面积越大。
 *
 * [ON_DEMAND] 的解法：提示词里**只暴露两个元工具**（检索 + 转发），真实工具的
 * 清单与参数形状按需检索 —— 模型要什么查什么，提示词长度与工具总数解耦。
 *
 * ## 与其它闸门的关系
 * 披露模式**只是可见性**，不是权限。转发调用（`call_tool`）在解包后走的是与直接调用
 * **完全相同**的守卫与审批链路（静态标志 ∪ 参数门控 ∪ 效果声明 ∪ 能力档位），
 * 因此它不构成任何权限旁路。这一点是本模式的硬约束，改实现时不得破坏。
 *
 * ⚠️ 纪律：与 [AiCapabilityMode] 一样，模式必须进入 core-agent 执行路径，
 * **不得只活在设置页**。
 */
@Serializable
enum class ToolDisclosureMode {
    /**
     * 全量披露（**默认档**）：工具清单完整进提示词，与引入本模式之前的行为逐字节一致。
     * 选它作默认是刻意的 —— 本模式的引入必须做到**零行为回归**。
     */
    FULL,

    /**
     * 按需披露：提示词只含检索与转发两个元工具，真实工具按需检索后转发执行。
     * 适合「工具较多 / 模型较小 / 上下文紧张」的场景。
     */
    ON_DEMAND,
    ;

    /** 是否需要在提示词里把真实工具清单替换成元工具（fail-safe：未知值按全量处理）。 */
    fun hidesToolCatalog(): Boolean = this == ON_DEMAND
}
